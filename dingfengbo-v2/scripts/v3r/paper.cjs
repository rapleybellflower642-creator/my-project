#!/usr/bin/env node
'use strict';

// Cache only the unchanging paper texture. Geometry, actors, weather, lettering
// and camera transforms remain in the per-frame SVG scene graph.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '../..');
sharp.concurrency(1);

(async () => {
  // Keep the authored SVG pattern as the source of truth for this generated asset.
  const source = fs.readFileSync(path.join(root, 'src/v3r/Environment.tsx'), 'utf8');
  const match = source.match(/<pattern id=\{`\$\{id\}-paper`\}([^>]*)>([\s\S]*?)<\/pattern>/);
  if (!match) throw new Error('Could not locate the authored paper pattern in Environment.tsx');
  const content = match[2].replace(/\bstrokeWidth=/g, 'stroke-width=');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="1080"><defs><pattern id="paper"${match[1]}>${content}</pattern></defs><rect width="1920" height="1080" fill="url(#paper)"/></svg>`;
  const png = await sharp(Buffer.from(svg), {density: 72}).png().toBuffer();
  const directory = path.join(root, 'public/v3r');
  fs.mkdirSync(directory, {recursive: true});
  fs.writeFileSync(path.join(directory, 'paper.png'), png);
  fs.writeFileSync(path.join(root, 'src/v3r/paper-data.ts'),
    '// Generated by node scripts/v3r/paper.cjs from Environment.tsx.\n' +
    `export const PAPER_DATA_URI = 'data:image/png;base64,${png.toString('base64')}';\n`);
  console.log(`Prepared transparent paper texture: 1920x1080, ${png.length} bytes.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
